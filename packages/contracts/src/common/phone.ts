import { z } from 'zod';

/**
 * Телефон клиента: свободная запись нормализуется в E.164 (`+<цифры>`).
 *
 * Почему валидируем на границе: салон в Москве, звонок по номеру — основной канал
 * подтверждения записи. Мусор в поле отсекается 400 на границе API и не попадает в БД,
 * где номер нужен для связи. Формат хранения один (E.164): так номер можно сравнивать,
 * маскировать и передавать в SMS-провайдера без разбора десятка вариантов написания.
 *
 * Валидатор не возвращает и не логирует введённое значение: тексты ошибок статические,
 * чтобы телефон (ПДн) не попадал в ответы API и логи клиента.
 */

/** Сколько символов может занимать запись номера с разделителями. */
const MAX_PHONE_LENGTH = 32;

/** Разрешённые символы: цифры, ведущий плюс и разделители записи номера. */
const ALLOWED_CHARS = /^[\d\s().+-]+$/;

/** Номер после удаления разделителей: необязательный плюс и цифры. */
const COMPACT_PHONE = /^\+?\d+$/;

/** Допустимая длина цифр в E.164: от 11 (`+1 202 555 0143`) до 15. */
const MIN_E164_DIGITS = 11;
const MAX_E164_DIGITS = 15;

/** Длина цифр российского номера в E.164 (`+7` и десять цифр). */
const RU_DIGITS = 11;

/**
 * Свободная запись телефона → E.164 (`+<цифры>`), либо `null`, если это не телефон.
 *
 * Разделители (пробелы, включая неразрывный, дефисы, скобки, точки) допустимы:
 * - российская форма без плюса: 11 цифр с ведущими `7`/`8` → `+7` и последние 10
 *   (`8 (912) 345-67-89` → `+79123456789`), либо 10 цифр с ведущей `9` → `+7` и эти 10
 *   (`9123456789` → `+79123456789`);
 * - международная форма: ведущий `+` и 11–15 цифр → как есть
 *   (`+1 202 555 0143` → `+12025550143`).
 *
 * Всё остальное считается не-телефоном: короткие и обрезанные номера (`1234567`,
 * `8 (912) 345-67-8`), лишние цифры, буквы, пустая строка.
 */
export function normalizePhone(input: string): string | null {
  const value = input.trim();
  if (value.length === 0 || value.length > MAX_PHONE_LENGTH) return null;
  if (!ALLOWED_CHARS.test(value)) return null;

  const compact = value.replace(/[\s().-]/g, '');
  if (!COMPACT_PHONE.test(compact)) return null;

  if (compact.startsWith('+')) {
    const digits = compact.slice(1);
    if (digits.length < MIN_E164_DIGITS || digits.length > MAX_E164_DIGITS) return null;
    return `+${digits}`;
  }

  // Без плюса запись читается как российская: плюс в начале означает международный формат.
  if (compact.length === RU_DIGITS && (compact.startsWith('7') || compact.startsWith('8'))) {
    return `+7${compact.slice(1)}`;
  }
  if (compact.length === RU_DIGITS - 1 && compact.startsWith('9')) {
    return `+7${compact}`;
  }
  return null;
}

/**
 * Телефон клиента: на входе свободная запись, на выходе E.164 (`+<цифры>`).
 * Валидация и нормализация совмещены: приложение получает уже канонический номер.
 *
 * Нормализуется в E.164 любой реальный номер: российский (`+7…`) и международный (`+1…`,
 * `+44…`). Основная форма — российская, но отказывать гостю из другой страны салон не должен:
 * записаться может приезжий или иностранец, а звонок по номеру нужен для подтверждения записи.
 * Поэтому правило мягче, чем «только РФ»: отклоняем не-телефоны, а не «не наш» формат.
 *
 * Обратная совместимость: поле было строкой и раньше, менять его тип или имя нельзя —
 * старые версии клиентов (кэш PWA, позже мобильное приложение) живут неделями. Плюс в начале
 * номера всегда означал международный формат, поэтому такие номера снова проходят валидацию,
 * а не превращаются в 400 на ровном месте.
 */
export const phoneSchema = z
  .string()
  .trim()
  .refine((value) => normalizePhone(value) !== null, {
    // Сообщение статическое: значение поля (ПДн) в текст ошибки не попадает.
    message: 'Укажите телефон в формате +7 XXX XXX-XX-XX или международный с +',
  })
  .transform((value): string => normalizePhone(value) ?? value);

export type Phone = z.infer<typeof phoneSchema>;

/** Маска российского номера: привычный для салона вид, видно последние две цифры. */
const RU_MASK_HEAD = '+7 (***) ***-**-';

/** Заглушка для значения, в котором нет ни одной цифры: показывать нечего. */
const EMPTY_MASK = '+***';

/**
 * Сколько цифр в коде страны. Таблицу кодов не тянем (контракты — без данных и справочников):
 * `+1` и `+7` — одна цифра, остальные распространённые коды — две.
 */
function countryCodeLength(digits: string): number {
  const first = digits.charAt(0);
  return first === '1' || first === '7' ? 1 : 2;
}

/** Российский номер: 11 цифр с ведущими `7`/`8` (в том числе записи в свободном формате). */
function isRussianDigits(digits: string): boolean {
  return digits.length === RU_DIGITS && (digits.startsWith('7') || digits.startsWith('8'));
}

/**
 * Маска номера: видно код страны и последние две цифры, остальные скрыты.
 *
 * Российский номер показывается привычно: `+79123456789` → `+7 (***) ***-**-89`.
 * Международный — в общем виде: `+12025550143` → `+1 ********43`.
 *
 * Возвращает строку всегда, даже для старых записей в свободном формате:
 * маска — не способ валидации, а способ показать клиенту, что номер принят,
 * не отдавая ПДн целиком ни в ответе, ни в кэше PWA.
 */
export function maskPhone(phone: string): string {
  const digits = phone.replace(/\D/g, '');
  if (isRussianDigits(digits)) return `${RU_MASK_HEAD}${digits.slice(-2)}`;
  // Кода страны и хвоста нет — скрывать нечего, но и показывать нечего.
  if (digits.length < 4) return EMPTY_MASK;

  const code = digits.slice(0, countryCodeLength(digits));
  const body = digits.slice(code.length);
  const hidden = '*'.repeat(Math.max(body.length - 2, 0));
  return `+${code} ${hidden}${body.slice(-2)}`;
}
